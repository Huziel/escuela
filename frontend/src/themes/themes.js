export const fonts = [
  { name: 'Inter', value: "'Inter', system-ui, -apple-system, sans-serif" },
  { name: 'Poppins', value: "'Poppins', system-ui, -apple-system, sans-serif" },
  { name: 'Roboto', value: "'Roboto', system-ui, -apple-system, sans-serif" },
  { name: 'JetBrains Mono', value: "'JetBrains Mono', 'Fira Code', monospace" },
]

export function applyTheme(themeName) {
  const theme = themes[themeName] || themes['crimson-glass']
  document.documentElement.setAttribute('data-theme', themeName)
  document.documentElement.setAttribute('data-theme-type', theme.type)
  Object.entries(theme.colors).forEach(([key, value]) => {
    document.documentElement.style.setProperty(key, value)
  })
  const primary = theme.colors['--color-primary']
  document.documentElement.style.setProperty('--color-primary-rgb', hexToRgb(primary))
  if (!theme.colors['--color-text']) {
    document.documentElement.style.setProperty('--color-text', theme.type === 'light' ? '#1F2937' : '#E6EDF3')
  }
  localStorage.setItem('sice-theme', themeName)
}

function hexToRgb(hex) {
  const result = /^#?([a-f\d]{2})([a-f\d]{2})([a-f\d]{2})$/i.exec(hex)
  return result ? `${parseInt(result[1], 16)}, ${parseInt(result[2], 16)}, ${parseInt(result[3], 16)}` : '198, 40, 40'
}

export function applyFont(fontFamily) {
  document.documentElement.style.setProperty('--font-family', fontFamily)
  localStorage.setItem('sice-font', fontFamily)
}

export function getSavedTheme() {
  return localStorage.getItem('sice-theme') || 'crimson-glass'
}

export function getSavedFont() {
  return localStorage.getItem('sice-font') || fonts[0].value
}

