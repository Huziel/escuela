export function applyIconStyle(name) {
  const style = iconStyles.find(s => s.value === name)
  let el = document.getElementById('icon-style')
  if (style && style.css) {
    if (!el) {
      el = document.createElement('style')
      el.id = 'icon-style'
      document.head.appendChild(el)
    }
    el.textContent = style.css
  } else if (el) {
    el.remove()
  }
  document.documentElement.setAttribute('data-icon-style', name || 'classic')
  localStorage.setItem('sice-icon-style', name || 'classic')
}

export function getSavedIconStyle() {
  return localStorage.getItem('sice-icon-style') || 'classic'
}
